#!/usr/bin/env python3
"""按配置的 DINOv3 ViT-L 和颜色权重排列商品候选。"""

import argparse
import json
import math
import time
import shutil
from pathlib import Path
import cv2
import numpy as np
import torch
import torch.nn.functional as F
from transformers import AutoModel
from app.tracking.stable_trajectory import select_stable_track
from app.catalog.product_catalog import load_features, validate_cabinet_id
from app.recognition.full_color import descriptor, decode_mask

from app import config

ROOT = config.LOCAL_ROOT
MODEL = config.LOCAL_MODEL


def hist(img, alpha=None):
    """计算图像中有效像素的平滑色相直方图。"""
    h, s, v = cv2.split(cv2.cvtColor(img, cv2.COLOR_BGR2HSV))
    mask = (s >= 60) & (v >= 45)
    if alpha is not None:
        mask &= alpha >= 128
    q = np.bincount((h[mask] // 5).astype(np.int32), minlength=36).astype(float)
    q = (np.roll(q, 2) + 4 * np.roll(q, 1) + 6 * q + 4 * np.roll(q, -1) + np.roll(q, -2)) / 16
    if q.sum():
        q /= q.sum()
    return q


def resolve(p):
    """将相对路径解析为项目根目录下的路径。"""
    p = Path(p).expanduser()
    return p if p.is_absolute() else ROOT / p


def main(argv=None, model=None):
    """读取检测结果和视频，按轨迹汇总商品匹配得分并输出报告。"""
    ap = argparse.ArgumentParser(
        description="Compare held-product boxes with cabinet SKU references using configured DINOv3-L and color weights."
    )
    ap.add_argument(
        "--detections",
        default=None,
        help="Detection results JSON generated by held_product_detect.py",
    )
    ap.add_argument(
        "--images", help="Original image directory; defaults to source from detection results"
    )
    ap.add_argument(
        "--video", required=True, help="Original video corresponding to the detection frames"
    )
    ap.add_argument(
        "--output",
        default=None,
        help="Output directory for annotated images; cleared before processing",
    )
    ap.add_argument(
        "--result",
        default=None,
        help="Output JSON report, default project root",
    )
    ap.add_argument(
        "--no-images",
        action="store_true",
        help="Skip annotated images when only the JSON result is needed",
    )
    ap.add_argument(
        "--limit", type=int, default=0, help="Process at most this many image records; 0 means all"
    )
    ap.add_argument(
        "--top", type=int, default=3, help="Number of ranked candidates to display (default 3)"
    )
    ap.add_argument(
        "--min-track-points",
        type=int,
        default=5,
        help="Minimum product observations required for final track ranking (default 5)",
    )
    ap.add_argument("--cabinet-id", required=True, help="柜子编码")
    args = ap.parse_args(argv)
    vector_weight, color_weight = config.vector_weight(), config.color_weight()
    validate_cabinet_id(args.cabinet_id)
    base = Path("tests/result") / args.cabinet_id
    args.detections = args.detections or base / "detections.json"
    args.output = args.output or base / "comparison_frames"
    args.result = args.result or base / "vector_compare_results.json"
    if args.limit < 0 or args.top < 1 or args.min_track_points < 1:
        ap.error("--limit must be >= 0; --top and --min-track-points must be >= 1")
    result_path = resolve(args.detections)
    data = json.loads(result_path.read_text())
    if data.get("cabinet_id") != args.cabinet_id:
        raise ValueError("检测报告的柜子编码与当前请求不一致")
    items = data.get("images")
    if not isinstance(items, list):
        raise ValueError("Expected detection results with an images array")
    items = items[: args.limit or None]
    image_dir = resolve(args.images or data.get("source", ""))
    if not image_dir.is_dir():
        raise FileNotFoundError(f"Original image directory does not exist: {image_dir}")
    out = resolve(args.output)
    out.mkdir(parents=True, exist_ok=True)
    if (
        out.resolve() == image_dir.resolve()
        or out.resolve() == result_path.parent.resolve()
        or out.resolve() in image_dir.resolve().parents
        or out.resolve() in result_path.resolve().parents
    ):
        raise ValueError("Output directory cannot contain original images or detection results")
    report_path = resolve(args.result)
    if (
        report_path.resolve() == result_path.resolve()
        or out.resolve() in report_path.resolve().parents
    ):
        raise ValueError(
            "Vector report must differ from input and be outside the image output directory"
        )
    catalog = load_features(args.cabinet_id)
    groups = {k: np.arange(len(v["features"])) for k, v in catalog.items()}
    cent = {}
    colors = {}
    for k, entry in catalog.items():
        feature_vectors = entry["features"]
        c = None
        for j, v in enumerate(feature_vectors):
            c = v.copy() if c is None else (c * j + v) / (j + 1)
            c /= np.linalg.norm(c)
        cent[k] = c
        colors[k] = entry["full_colors"]
    total_vectors = sum(len(x["features"]) for x in catalog.values())
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA unavailable; this script uses the local GPU")
    torch.set_num_threads(4)
    cv2.setNumThreads(2)
    start = time.perf_counter()
    if model is None:
        model = AutoModel.from_pretrained(str(MODEL), local_files_only=True).eval().cuda()
    init = time.perf_counter() - start
    video = resolve(args.video)
    if not video.is_file():
        raise FileNotFoundError(f"Original video does not exist: {video}")
    cap = cv2.VideoCapture(str(video))
    if not cap.isOpened():
        raise ValueError(f"Cannot open original video: {video}")
    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    video_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    cap.release()
    boxes = [None] * video_frames
    embeddings = {}
    frame_items = {}
    mean = torch.tensor([0.485, 0.456, 0.406], device="cuda")[None, :, None, None]
    std = torch.tensor([0.229, 0.224, 0.225], device="cuda")[None, :, None, None]
    for frame_index, item in enumerate(items, 1):
        name = item["source"]
        if Path(name).name != name:
            raise ValueError(f"Invalid image name: {name}")
        stem = Path(name).stem
        frame = int(stem) if stem.isdigit() else frame_index
        if frame < 1 or frame > video_frames or frame in frame_items:
            raise ValueError(f"Invalid or duplicate video frame: {frame}")
        frame_items[frame] = item
        box = item.get("rendered_box")
        if box is None:
            continue
        img = cv2.imread(str(image_dir / name))
        if img is None:
            raise FileNotFoundError(image_dir / name)
        if img.shape[:2] != (height, width):
            raise ValueError(f"Image dimensions do not match video: {name}")
        x1, y1 = max(0, math.floor(box[0])), max(0, math.floor(box[1]))
        x2, y2 = min(width, math.ceil(box[2])), min(height, math.ceil(box[3]))
        crop = img[y1:y2, x1:x2]
        if not crop.size:
            raise ValueError(f"Empty product crop in {name}: {box}")
        encoded = item.get("product_mask")
        if not encoded:
            raise ValueError(f"Missing product mask for {name}; rerun product detection")
        mask = decode_mask(encoded)
        if mask.shape != crop.shape[:2] or not mask.any():
            raise ValueError(f"Invalid product mask for {name}")
        rgb = torch.from_numpy(np.ascontiguousarray(crop[:, :, ::-1])).cuda().permute(2, 0, 1)
        weight = torch.from_numpy(mask).cuda()
        with torch.inference_mode():
            image = (
                F.interpolate(
                    (rgb * weight.unsqueeze(0))[None].float(),
                    size=(224, 224),
                    mode="bilinear",
                    align_corners=False,
                )
                .round()
                .div_(255)
            )
            embeddings[frame] = (
                F.normalize(model(pixel_values=(image - mean) / std).pooler_output, dim=1)[0]
                .cpu()
                .numpy()
            )
        boxes[frame - 1] = box
    primary, track_summary = select_stable_track(
        video, boxes, width, height, embeddings, min_points=args.min_track_points
    )
    primary_id = primary["track_id"] if primary else None
    selected = {p["frame"]: p for p in primary["points"]} if primary else {}
    rejected_motion_points = set()
    for p in out.iterdir():
        if p.is_dir() and not p.is_symlink():
            shutil.rmtree(p)
        else:
            p.unlink()
    rows = []
    processing = time.perf_counter()
    for frame_index, item in enumerate(items, 1):
        name = item["source"]
        if Path(name).name != name:
            raise ValueError(f"Invalid image name: {name}")
        raw_box = item.get("rendered_box")
        stem = Path(name).stem
        frame = int(stem) if stem.isdigit() else frame_index
        point = selected.get(frame)
        is_primary = point is not None
        candidate = (
            {
                "track_id": primary_id,
                "point": point["point"],
                "path": [p for p in primary["points"] if p["frame"] <= frame],
            }
            if point
            else None
        )
        box = raw_box if is_primary else None
        rank = []
        if args.no_images and box is None:
            rows.append(
                {
                    "source": name,
                    "box": None,
                    "raw_detection_box": raw_box,
                    "excluded_nonprimary": bool(raw_box is not None),
                    "detection_score": item.get("selected", {}).get("score")
                    if item.get("selected")
                    else None,
                    "ranking": [],
                    "trajectory": None,
                }
            )
            continue
        img = cv2.imread(str(image_dir / name))
        if img is None:
            raise FileNotFoundError(image_dir / name)
        h, w = img.shape[:2]
        if box is not None:
            x1, y1 = max(0, math.floor(box[0])), max(0, math.floor(box[1]))
            x2, y2 = min(w, math.ceil(box[2])), min(h, math.ceil(box[3]))
            crop = img[y1:y2, x1:x2]
            if not crop.size:
                raise ValueError(f"Empty product crop in {name}: {box}")
            encoded = item.get("product_mask")
            if not encoded:
                raise ValueError(f"Missing product mask for {name}; rerun product detection")
            mask = decode_mask(encoded)
            if mask.shape != crop.shape[:2] or not mask.any():
                raise ValueError(f"Invalid product mask for {name}")
            rgb = torch.from_numpy(np.ascontiguousarray(crop[:, :, ::-1])).cuda().permute(2, 0, 1)
            weight = torch.from_numpy(mask).cuda()
            with torch.inference_mode():
                c = descriptor(rgb, weight).cpu().numpy()
                masked = rgb * weight.unsqueeze(0)
                image = (
                    F.interpolate(
                        masked[None].float(), size=(224, 224), mode="bilinear", align_corners=False
                    )
                    .round()
                    .div_(255)
                )
                mean = torch.tensor([0.485, 0.456, 0.406], device="cuda")[None, :, None, None]
                std = torch.tensor([0.229, 0.224, 0.225], device="cuda")[None, :, None, None]
                q = (
                    F.normalize(model(pixel_values=(image - mean) / std).pooler_output, dim=1)
                    .cpu()
                    .numpy()[0]
                )
            for k, idx in groups.items():
                vs = max(float(q @ cent[k]), float(np.max(catalog[k]["features"] @ q)))
                cs = max(float(np.sqrt(c * ref).sum()) for ref in colors[k])
                rank.append({"sku": k, "combined": vector_weight * vs + color_weight * cs, "vector": vs, "color": cs})
            rank.sort(key=lambda z: -z["combined"])
            cv2.rectangle(img, (x1, y1), (x2, y2), (0, 255, 255), 3)
            for i, v in enumerate(rank[: args.top]):
                label = f"Frame {i + 1}: SKU {v['sku']} score {v['combined']:.3f}"
                y = max(26, y1 - 8 - i * 29)
                cv2.putText(
                    img, label, (x1, y), cv2.FONT_HERSHEY_SIMPLEX, 0.75, (0, 0, 0), 5, cv2.LINE_AA
                )
                cv2.putText(
                    img,
                    label,
                    (x1, y),
                    cv2.FONT_HERSHEY_SIMPLEX,
                    0.75,
                    (0, 255, 255),
                    2,
                    cv2.LINE_AA,
                )
        observation = candidate if is_primary else None
        if observation:
            path = [
                p
                for p in observation["path"]
                if (observation["track_id"], p["frame"]) not in rejected_motion_points
            ]
            for a, b in zip(path, path[1:]):
                if b["frame"] - a["frame"] == 1:
                    cv2.line(
                        img,
                        tuple(map(round, a["point"])),
                        tuple(map(round, b["point"])),
                        (255, 160, 0),
                        4,
                        cv2.LINE_AA,
                    )
            if (observation["track_id"], frame) not in rejected_motion_points:
                cx, cy = map(round, observation["point"])
                cv2.circle(img, (cx, cy), 6, (255, 160, 0), -1, cv2.LINE_AA)
            t = f"Track {observation['track_id']}"
            cv2.putText(img, t, (15, 35), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 0, 0), 5, cv2.LINE_AA)
            cv2.putText(
                img, t, (15, 35), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (255, 160, 0), 2, cv2.LINE_AA
            )
        footer = f"{name} | DINOv3-L {vector_weight:g} + color {color_weight:g}"
        (tw, th), _ = cv2.getTextSize(footer, cv2.FONT_HERSHEY_SIMPLEX, 0.6, 2)
        cv2.rectangle(img, (max(0, w - tw - 20), h - th - 18), (w, h), (0, 0, 0), -1)
        cv2.putText(
            img,
            footer,
            (max(0, w - tw - 10), h - 10),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.6,
            (255, 255, 255),
            2,
            cv2.LINE_AA,
        )
        if not args.no_images and not cv2.imwrite(str(out / name), img):
            raise RuntimeError(f"Unable to write {out / name}")
        rows.append(
            {
                "source": name,
                "box": box,
                "raw_detection_box": raw_box,
                "excluded_nonprimary": bool(raw_box is not None and not is_primary),
                "detection_score": item.get("selected", {}).get("score")
                if item.get("selected")
                else None,
                "ranking": rank,
                "trajectory": observation,
            }
        )
        if rank:
            print(
                name,
                "top",
                [(v["sku"], round(v["combined"], 3)) for v in rank[: args.top]],
                flush=True,
            )
    tracks = [{"track_id": primary_id, "points": primary["points"]}] if primary else []
    by_track = {t["track_id"]: [] for t in tracks}
    for row in rows:
        if row["trajectory"] and row["ranking"]:
            by_track[row["trajectory"]["track_id"]].append(row)
    for track in tracks:
        observations = by_track[track["track_id"]]
        rankings = []
        if len(observations) < args.min_track_points:
            track["observation_count"] = len(observations)
            track["final_ranking"] = []
            track["final_sku"] = None
            track["decision"] = "excluded_short_track"
            continue
        for k in groups:
            measurements = [next(v for v in r["ranking"] if v["sku"] == k) for r in observations]
            if not measurements:
                continue
            v = float(np.mean([m["vector"] for m in measurements]))
            c = float(np.mean([m["color"] for m in measurements]))
            rankings.append({"sku": k, "combined": vector_weight * v + color_weight * c, "vector": v, "color": c})
        rankings.sort(key=lambda v: (-v["combined"], v["sku"]))
        track["observation_count"] = len(observations)
        track["final_ranking"] = rankings
        track["final_sku"] = rankings[0]["sku"] if rankings else None
        track["decision"] = "candidate" if rankings else "unavailable"
    final = {t["track_id"]: t for t in tracks}
    for row in rows:
        if not row["trajectory"]:
            continue
        if args.no_images:
            row["final_track_sku"] = final[row["trajectory"]["track_id"]]["final_sku"]
            continue
        t = final[row["trajectory"]["track_id"]]
        row["final_track_sku"] = t["final_sku"]
        img = cv2.imread(str(out / row["source"]))
        assert img is not None
        text = (
            f"Final track {t['track_id']}: SKU {t['final_sku']} ({t['observation_count']} frames)"
            if t["final_sku"] is not None
            else f"Track {t['track_id']}: short track excluded"
            if t["decision"] == "excluded_short_track"
            else f"Final track {t['track_id']}: no SKU"
        )
        h, w = img.shape[:2]
        (tw, th), _ = cv2.getTextSize(text, cv2.FONT_HERSHEY_SIMPLEX, 0.7, 2)
        x = max(0, w - tw - 10)
        y = max(th + 4, h - 42)
        cv2.rectangle(img, (max(0, x - 4), y - th - 5), (w, y + 5), (0, 0, 0), -1)
        cv2.putText(
            img, text, (x, y), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255, 255, 255), 2, cv2.LINE_AA
        )
        assert cv2.imwrite(str(out / row["source"]), img)
    report = {
        "cabinet_id": args.cabinet_id,
        "source": str(image_dir),
        "detection_results": str(result_path),
        "model": str(MODEL),
        "references": total_vectors,
        "reference_skus": len(groups),
        "weights": {"vector": vector_weight, "color": color_weight},
        "frames": len(rows),
        "frames_compared": sum(bool(x["ranking"]) for x in rows),
        "model_initialization_seconds": init,
        "processing_seconds": time.perf_counter() - processing,
        "trajectory_method": "shared stable trajectory using video motion and DINOv3 appearance",
        "final_decision_method": "offline per-track mean of per-frame vector and color scores combined using configured weights; highest ranked candidate; no binding while tracking",
        "min_track_points": args.min_track_points,
        "trajectory_selection": "eligible stable track maximizing verified motion; minimum displacement 5 pixels",
        "motion_summary": track_summary,
        "selected_track_id": primary_id,
        "nonselected_track_count": track_summary["tracks"] - (1 if primary_id is not None else 0),
        "tracks": tracks,
        "images": rows,
    }
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    print(f"DONE {len(rows)} images, {report['frames_compared']} boxes; output {out}", flush=True)
    return report


if __name__ == "__main__":
    from app.logging import setup_logging

    setup_logging("vector-compare")
    main()
